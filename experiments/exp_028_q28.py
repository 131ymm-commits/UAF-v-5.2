"""
UAF v5.2 — EXP 028: Q28 — Оптогенетическая стимуляция (Leifer 2023)
=====================================================================
ГИПОТЕЗА: на ИДЕАЛЬНЫХ данных (сырой сигнал + известные оптогенетические
          возмущения известных нейронов) метод Q24 наконец прочитает
          сетевой het — снимется проблема Q27 (кальций гладкий, нет
          настоящих возмущений).

ДАННЫЕ:  Randi/Leifer 2023 (Nature), neural signal propagation atlas.
          10 записей, 67–88 валидных нейронов, ~2 Гц, 4029 точек.
          СЫРОЙ GCaMP без сглаживания, со всеми артефактами стимуляции.
          _stim_neurons + _stim_volume_i: какой нейрон и когда возмущён
          оптогенетически (19–54 стимуляции на запись).
          Это РОДНАЯ постановка метода Q24: возмущение известного нейрона.

МЕТОД:   для каждой стимуляции измерить ответ сети (изменение активности
          после vs до). Два теста по 10 записям:
          (1) каузальный (sanity): вызывает ли стимуляция ответ в целевом
              нейроне? — проверка, что данные вообще про распространение.
          (2) het-механизм: различается ли размер каскадов от разных
              стимулированных нейронов больше, чем от случайных окон?
              (хабы → большие каскады, листья → малые → высокий CV).
          ОБЯЗАТЕЛЬНЫЙ нулевой контроль (урок Q27).

ОТВЕТ:   ДВА ЧЁТКИХ РЕЗУЛЬТАТА.

          (1) КАУЗАЛЬНОЕ РАСПРОСТРАНЕНИЕ РЕАЛЬНО: 8 из 10 записей —
              стимуляция значимо вызывает ответ целевого нейрона
              (median p=0.011). Сигнал распространяется по сети.

          (2) het-МЕХАНИЗМ Q24 НЕ ПОДТВЕРЖДЁН: средний z=−0.15±0.72,
              НИ В ОДНОЙ из 10 записей z>2. Размах каскадов от реальных
              стимуляций неотличим от случайных окон.

ВЫВОД (решающий): даже на ИДЕАЛЬНЫХ данных — сырой сигнал, известные
          возмущения известных нейронов, настоящая оптогенетика — механизм
          Q24 (хабы → разброс ответов ∝ het) НЕ читается. Это не проблема
          гладкости кальция (Q27). Это глубже: разброс откликов в реальной
          нейронной сети НЕ определяется степенной гетерогенностью так,
          как в UAF-ABM. Реальная сеть откликается иначе, чем модель.

ВЕРДИКТ: НЕ ПОДТВЕРЖДЕНО (окончательно). Метод операционализации UAF
          (het из разброса динамических откликов) НЕ переносится на
          реальную нейронную активность — ни на кальций (Q27), ни на
          сырой стимуляционный сигнал (Q28). Каузальное распространение
          есть, но его статистика не следует UAF-механизму.

          Это честная ГРАНИЦА теории: UAF-инварианты валидны как
          свойства модели (Фаза 1, реальный коннектом Q22), но
          динамическая сигнатура het (Фаза 2) не реализуется в реальных
          нейронных откликах. Операционализация через динамику не работает
          на этой системе.

Запуск:
    PYTHONPATH=. python experiments/exp_028_q28.py
    (требует распакованный Leifer2023, файлы 90-99)
"""

import numpy as np
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from scipy.stats import ttest_ind


LEIFER_DIR = 'leifer/Leifer2023'
RECORDINGS = [90, 91, 92, 93, 94, 95, 96, 97, 98, 99]


def load_rec(num, base=LEIFER_DIR):
    g  = np.loadtxt(f'{base}/{num}_gcamp.txt')
    sv = np.loadtxt(f'{base}/{num}_stim_volume_i.txt').astype(int)
    sn = np.loadtxt(f'{base}/{num}_stim_neurons.txt').astype(int)
    return g, sv, sn


def clean(g, max_nan=0.3):
    """Keep neurons with <max_nan NaN fraction; interpolate remaining gaps."""
    keep = np.isnan(g).mean(axis=0) < max_nan
    g2 = g[:, keep].copy()
    for i in range(g2.shape[1]):
        x = g2[:, i]; nans = np.isnan(x)
        if nans.any():
            x[nans] = np.interp(np.flatnonzero(nans), np.flatnonzero(~nans), x[~nans])
            g2[:, i] = x
    return g2, np.flatnonzero(keep)


def normalize(X, pct=(2, 98)):
    A = np.zeros_like(X)
    for i in range(X.shape[1]):
        x = X[:, i]
        lo, hi = np.percentile(x, pct[0]), np.percentile(x, pct[1])
        A[:, i] = np.clip((x - lo) / (hi - lo + 1e-9), 0, 1)
    return A


def response_magnitude(A, st, pre=5, post=10):
    """Per-neuron activity change after stim vs baseline before."""
    if st - pre < 0 or st + post >= len(A):
        return None
    return np.abs(A[st:st+post].mean(axis=0) - A[st-pre:st].mean(axis=0))


# ── EXP 028-A: Single recording deep-dive ────────────────────────────────────
def exp_028_a():
    print("\n" + "="*70)
    print("EXP 028-A  Запись 98: структура стимул-ответа")
    print("="*70)
    g, sv, sn = load_rec(98)
    g2, kept = clean(g)
    A = normalize(g2)
    print(f"""
  Сырой GCaMP: {g.shape[1]} нейронов, {len(g)} точек, ~2 Гц
  После чистки NaN: {g2.shape[1]} нейронов (<30% пропусков)
  Стимуляций: {(sn>=0).sum()} валидных (известный нейрон + время)

  Это родная постановка Q24: знаем КАКОЙ нейрон и КОГДА возмущён.
""")
    casc = []
    for st, snk in zip(sv, sn):
        if snk < 0:
            continue
        rm = response_magnitude(A, st)
        if rm is not None:
            casc.append((rm > 0.1).sum())
    casc = np.array(casc)
    print(f"  Размер каскада (нейронов отвечает на стимул): "
          f"{casc.mean():.1f} ± {casc.std():.1f}, диапазон [{casc.min()},{casc.max()}]")
    print(f"  CV каскадов = {casc.std()/casc.mean():.3f}")
    print(f"  (высокий CV = хабы дают большие каскады, листья малые)")


# ── EXP 028-B: Ensemble — causal + mechanism tests ───────────────────────────
def exp_028_b():
    print("\n" + "="*70)
    print("EXP 028-B  Ансамбль 10 записей: каузальность + механизм")
    print("="*70)
    print(f"\n  {'rec':>4}  {'neur':>5}  {'stim':>5}  {'causal_p':>9}  "
          f"{'het_z':>7}  {'casc_CV':>8}")
    print("  " + "-"*46)

    np.random.seed(0)
    causal_ps, het_zs = [], []
    for num in RECORDINGS:
        try:
            g, sv, sn = load_rec(num)
        except Exception:
            continue
        g2, kept = clean(g)
        if g2.shape[1] < 20:
            continue
        A = normalize(g2)
        idx_map = {o: n for n, o in enumerate(kept)}

        self_r, ctrl_r, casc = [], [], []
        for st, snk in zip(sv, sn):
            if snk < 0:
                continue
            rm = response_magnitude(A, st)
            if rm is None:
                continue
            casc.append((rm > 0.1).sum())
            if snk in idx_map:
                ni = idx_map[snk]
                self_r.append(rm[ni])
                rt = np.random.randint(10, len(A) - 10)
                rmc = response_magnitude(A, rt)
                if rmc is not None:
                    ctrl_r.append(rmc[ni])
        casc = np.array(casc)
        cp = ttest_ind(self_r, ctrl_r)[1] if len(self_r) > 3 and len(ctrl_r) > 3 else np.nan
        casc_cv = casc.std() / casc.mean() if casc.mean() > 0 else 0

        rand = []
        for _ in range(200):
            ft = np.random.randint(10, len(A) - 10, size=len(casc))
            rc = np.array([(response_magnitude(A, f) > 0.1).sum()
                           for f in ft if response_magnitude(A, f) is not None])
            rand.append(rc.std() / rc.mean() if rc.mean() > 0 else 0)
        rand = np.array(rand)
        hz = (casc_cv - rand.mean()) / rand.std() if rand.std() > 0 else 0
        causal_ps.append(cp); het_zs.append(hz)
        print(f"  {num:>4}  {g2.shape[1]:>5}  {len(casc):>5}  {cp:>9.3f}  "
              f"{hz:>+7.2f}  {casc_cv:>8.3f}")

    causal_ps = np.array([p for p in causal_ps if not np.isnan(p)])
    het_zs = np.array(het_zs)
    print(f"""
  КАУЗАЛЬНОСТЬ (стим→целевой нейрон):
    {(causal_ps<0.05).sum()}/{len(causal_ps)} записей значимы, median p={np.median(causal_ps):.3f}
    → распространение сигнала РЕАЛЬНО

  het-МЕХАНИЗМ (CV каскадов vs случайные окна):
    средний z={het_zs.mean():+.2f} ± {het_zs.std():.2f}
    записей с z>2: {(het_zs>2).sum()}/{len(het_zs)}
    → механизм Q24 НЕ подтверждён
""")
    return causal_ps, het_zs


