"""
UAF v5.2 — EXP 027: Q27 — Ансамбль червей + нулевой контроль
==============================================================
ГИПОТЕЗА: het≈1.3 из Q25 воспроизводится across animals → устойчивое
          свойство, подтверждающее, что метод Q24 читает сетевой het.

ДАННЫЕ:  Dag et al 2023, 15 червей whole-brain кальциевый имейджинг
          (swf415_no_id: 8, swf702_with_id: 7). 128–167 нейронов каждый.

МЕТОД:   het из rate_cv для каждого червя + КРИТИЧЕСКИЙ нулевой контроль:
          фазовая рандомизация (разрушает кросс-нейронную структуру и
          временные корреляции). Если реальный het > нулевого — сигнал
          несёт сетевую структуру. Если нет — rate_cv измеряет шум.

ОТВЕТ:   ДВА РЕЗУЛЬТАТА — оба важные, второй переворачивает интерпретацию.

          (1) ВОСПРОИЗВОДИМОСТЬ: het = 1.31 ± 0.06 across 15 червей,
              CV=4.8%, диапазон [1.18, 1.42]. Очень устойчивое число,
              численно близко к коннектомному 1.58, далеко от
              однородного 1.0.

          (2) НУЛЕВОЙ КОНТРОЛЬ ПРОВАЛЕН: фазово-рандомизированный het =
              1.39 ± 0.04 — ВЫШЕ реального (1.31). Парный t-тест:
              t=−8.4, p=7.6e-07. Реальная динамика МЕНЕЕ гетерогенна по
              rate_cv, чем разрушенная.

          ИНТЕРПРЕТАЦИЯ: rate_cv на кальции НЕ изолирует сетевую
          гетерогенность. Он смешивает: кинетику кальция (гладкость),
          индивидуальную вариабельность нейронов, и (слабо) структуру
          сети. Фазовая рандомизация делает траектории «острее» →
          больше разброс скоростей → выше rate_cv. Значит механизм Q24
          (хабы растут резко → разброс скоростей ∝ het) на кальции НЕ
          работает чисто.

ВЕРДИКТ: НЕ ПОДТВЕРЖДЕНО. het≈1.31 воспроизводим как ЧИСЛО, но его
          интерпретация как считывания сетевого het механизмом Q24 НЕ
          поддержана контролем. Совпадение с коннектомным диапазоном
          (1.3–1.6) — вероятно численное совпадение, не подтверждение
          механизма. Метод Q24 не переносится на кальций мехнистически
          корректно.

          Это честный отрицательный результат уровня механизма, несмотря
          на «красивое» воспроизводимое число. Контроль спас от ложного
          вывода.

Запуск:
    PYTHONPATH=. python experiments/exp_027_q27.py
    (требует распакованный Dag2023, 15 h5 файлов)
"""

import numpy as np
import h5py
import glob
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from scipy.stats import ttest_rel


DATA_GLOB = 'worms/Dag2023/*/*.h5'
CONNECTOME_HET = 1.58
CAL_SLOPE = 1.160
CAL_INTER = 0.876


def load_traces(fp):
    f = h5py.File(fp, 'r')
    if '/gcamp/traces_array_F_F20' in f:
        tr = f['/gcamp/traces_array_F_F20'][:]
    else:
        tr = f['/gcamp/trace_array'][:]
    f.close()
    return tr[:, ~np.isnan(tr).any(axis=0)]


def normalize(traces, pct=(2, 98)):
    A = np.zeros_like(traces)
    for i in range(traces.shape[1]):
        x = traces[:, i]
        lo, hi = np.percentile(x, pct[0]), np.percentile(x, pct[1])
        A[:, i] = np.clip((x - lo) / (hi - lo + 1e-9), 0, 1)
    return A


def rate_cv(A):
    r = np.array([np.abs(np.diff(A[:, i])).max() for i in range(A.shape[1])])
    return r.std() / r.mean() if r.mean() > 0 else 0.0


def het_of(traces):
    return CAL_SLOPE * rate_cv(normalize(traces)) + CAL_INTER


def phase_randomize(x):
    Xf = np.fft.rfft(x - x.mean())
    ph = np.exp(1j * np.random.uniform(0, 2*np.pi, len(Xf)))
    ph[0] = 1
    return np.fft.irfft(Xf * ph, n=len(x)) + x.mean()


# ── EXP 027-A: Ensemble het ──────────────────────────────────────────────────
def exp_027_a(files):
    print("\n" + "="*70)
    print("EXP 027-A  het across ансамбль из 15 червей (Dag 2023)")
    print("="*70)
    print(f"\n  {'worm':>16}  {'N':>4}  {'T':>5}  {'rate_cv':>8}  {'het':>6}")
    print("  " + "-"*46)

    hets = []
    for fp in files:
        tr = load_traces(fp)
        rcv = rate_cv(normalize(tr))
        het = CAL_SLOPE * rcv + CAL_INTER
        hets.append(het)
        name = fp.split('/')[-1].replace('-data.h5', '')
        print(f"  {name:>16}  {tr.shape[1]:>4}  {tr.shape[0]:>5}  "
              f"{rcv:>8.4f}  {het:>6.3f}")

    hets = np.array(hets)
    print(f"""
  het = {hets.mean():.3f} ± {hets.std():.3f}  (CV={hets.std()/hets.mean():.3f})
  диапазон [{hets.min():.3f}, {hets.max():.3f}], медиана {np.median(hets):.3f}
  Коннектом=1.58, однородный=1.0

  ВОСПРОИЗВОДИМО: het — устойчивое число across червей (CV<5%).
""")
    return hets


# ── EXP 027-B: Critical null control ─────────────────────────────────────────
def exp_027_b(files):
    print("\n" + "="*70)
    print("EXP 027-B  КРИТИЧЕСКИЙ контроль: фазовая рандомизация")
    print("="*70)
    print(f"""
  Нулевая модель: фазовая рандомизация каждого нейрона разрушает
  кросс-нейронную структуру и временные корреляции. Если механизм Q24
  верен (разброс скоростей ∝ сетевой het), реальный het должен быть
  ВЫШЕ нулевого. Проверяем.
""")
    print(f"  {'worm':>16}  {'het_real':>9}  {'het_null':>9}  {'real>null?'}")
    print("  " + "-"*48)

    np.random.seed(0)
    real_l, null_l = [], []
    for fp in files:
        tr = load_traces(fp)
        het_real = CAL_SLOPE * rate_cv(normalize(tr)) + CAL_INTER
        nulls = []
        for _ in range(20):
            tr_n = np.zeros_like(tr)
            for i in range(tr.shape[1]):
                tr_n[:, i] = phase_randomize(tr[:, i])
            nulls.append(CAL_SLOPE * rate_cv(normalize(tr_n)) + CAL_INTER)
        het_null = np.mean(nulls)
        real_l.append(het_real); null_l.append(het_null)
        name = fp.split('/')[-1].replace('-data.h5', '')
        flag = 'yes' if het_real > het_null else 'NO'
        print(f"  {name:>16}  {het_real:>9.3f}  {het_null:>9.3f}  {flag}")

    real_a = np.array(real_l); null_a = np.array(null_l)
    t, p = ttest_rel(real_a, null_a)
    diff = real_a - null_a
    print(f"""
  Реальный het:  {real_a.mean():.3f} ± {real_a.std():.3f}
  Нулевой het:   {null_a.mean():.3f} ± {null_a.std():.3f}
  Разность:      {diff.mean():+.3f} ± {diff.std():.3f}
  Парный t-тест: t={t:.2f}, p={p:.2e}

  КОНТРОЛЬ ПРОВАЛЕН: реальный het НИЖЕ нулевого ({real_a.mean():.2f}<{null_a.mean():.2f}).
  rate_cv на кальции НЕ изолирует сетевую гетерогенность.
""")
    return real_a, null_a


# ── EXP 027-C: Diagnosis ─────────────────────────────────────────────────────
def exp_027_c():
    print("\n" + "="*70)
    print("EXP 027-C  Диагноз: что измеряет rate_cv на кальции?")
    print("="*70)
    print(f"""
  Почему фазовая рандомизация даёт БОЛЬШИЙ rate_cv?
  Рандомизация удаляет временные корреляции → траектории становятся
  «острее» (больше резких скачков) → больше max|dA/dt| и его разброс.
  Реальный кальций ГЛАДКИЙ (медленная кинетика) → скорости сжаты.

  Значит rate_cv на кальции смешивает:
    • кинетику кальция (гладкость сигнала)     ← доминирует
    • индивидуальную вариабельность нейронов
    • структуру сети                            ← слабый вклад

  Механизм Q24 (хабы растут резче → разброс скоростей ∝ het) работал на
  ЧИСТОЙ модельной динамике, но на кальции тонет в кинетике сигнала.

  Воспроизводимое het≈1.31 — реальное устойчивое число, но это свойство
  КАЛЬЦИЕВОГО СИГНАЛА вида, а НЕ валидированное считывание сетевого het.
""")


